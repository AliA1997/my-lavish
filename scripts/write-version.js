#!/usr/bin/env node
// Writes src/version.js from package.json, so the CLI never reads package.json at run time
// (a single-executable build has no package.json next to it).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { version } = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
const file = path.join(ROOT, "src", "version.js");
const text = `// Generated by scripts/write-version.js from package.json. Do not edit.\nexport const VERSION = ${JSON.stringify(version)};\n`;
if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) fs.writeFileSync(file, text);
console.log(`src/version.js: ${version}`);
